"""
Generate the synthetic example dataset and the CSV templates.

Run from backend/:  python scripts/generate_example_dataset.py

Everything produced here is SYNTHETIC. The example files are exported from the
seeded demonstration fleet (one aircraft, individual component instances) and
its chronologically consistent synthetic history generated by the hidden
reference models (services/history.py, deterministic seeds). They can be
re-imported through the application's CSV import in the documented order:
flight_schedule → flight_actuals → flight_observations → inspection_findings /
maintenance_records.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.db import Database  # noqa: E402
from app.services.csv_import import TEMPLATES, template_csv  # noqa: E402
from app.services.seed import seed_database  # noqa: E402

ROOT = Path(__file__).resolve().parents[2] / "data"
CID = "ENG-MOUNT-001"


def main() -> None:
    (ROOT / "templates").mkdir(parents=True, exist_ok=True)
    (ROOT / "example_dataset").mkdir(parents=True, exist_ok=True)
    for name in TEMPLATES:
        (ROOT / "templates" / f"{name}.csv").write_text(template_csv(name))

    db = Database(":memory:")
    seed_database(db)
    flights = sorted(db.list("flights"), key=lambda f: f["sequence"])

    # flight schedule (scheduled information of every flight, completed or not)
    with (ROOT / "example_dataset" / "flight_schedule_AIRCRAFT-001.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["aircraft_id", "flight_date", "route_or_mission", "duration_min", "landing_cycles", "payload_fraction", "expected_temperature_c", "expected_environment", "notes"])
        for fl in flights:
            s = fl["scheduled"]
            w.writerow([fl["aircraft_id"], fl["flight_date"], fl["route_or_mission"], s["duration_min"], s["landing_cycles"], s["payload_fraction"], s["expected_temperature_c"], s["expected_environment"], f"{fl['id']} ({fl['status']})"])

    # flight actuals of completed flights
    with (ROOT / "example_dataset" / "flight_actuals_AIRCRAFT-001.csv").open("w", newline="") as f:
        w = csv.writer(f)
        cols = ["flight_id", "duration_min", "landing_cycles", "load_factor", "load_variation", "manoeuvre_intensity", "temperature_c", "pressure_factor", "vibration_level", "environment", "operating_intensity", "source"]
        w.writerow(cols)
        for fl in flights:
            if fl["status"] == "completed":
                a = fl["actual"]
                w.writerow([fl["id"]] + [a.get(c) for c in cols[1:]])

    # component observations of ENG-MOUNT-001 for the first three completed flights (30 s samples)
    with (ROOT / "example_dataset" / f"flight_observations_{CID}.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["component_id", "flight_id", "t_s", "phase", "load_kN", "strain_microstrain", "temperature_c", "pressure_bar", "vibration_g"])
        for obs in sorted(db.list("flight_records", {"component_id": CID}), key=lambda o: o["flight_sequence"])[:3]:
            ch = obs["channels"]
            for i, t in enumerate(ch["t_s"]):
                w.writerow([CID, obs["flight_id"], t, ch["phase"][i], round(ch["load_kN"][i], 3), round(ch["strain_microstrain"][i], 2), round(ch["temperature_c"][i], 3), "", round(ch["vibration_g"][i], 4)])

    # inspection findings and maintenance records of the whole fleet history
    with (ROOT / "example_dataset" / "inspection_findings.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["component_id", "inspection_date", "method", "observed_defect", "quantity", "measured_value", "unit", "measurement_uncertainty", "confidence", "source", "notes"])
        for i in sorted(db.list("inspections"), key=lambda i: i["inspection_date"]):
            w.writerow([i["component_id"], i["inspection_date"], i["method"], i["observed_defect"], i.get("quantity") or "", i.get("measured_value") if i.get("measured_value") is not None else "", i.get("unit") or "", i.get("measurement_uncertainty") if i.get("measurement_uncertainty") is not None else "", i["confidence"], i["source"], i["notes"]])
    with (ROOT / "example_dataset" / "maintenance_records.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["component_id", "maintenance_date", "activity", "repair_or_replacement", "damage_after_quantity", "damage_after_value", "maintenance_reference", "notes"])
        for m in sorted(db.list("maintenance"), key=lambda m: m["maintenance_date"]):
            da = m.get("damage_after") or {}
            q = next(iter(da), "")
            w.writerow([m["component_id"], m["maintenance_date"], m["activity"], m["repair_or_replacement"], q, da.get(q, "") if q else "", m["maintenance_reference"], "SYNTHETIC"])

    # operational summary records of ENG-MOUNT-001 (one per completed flight)
    with (ROOT / "example_dataset" / "operational_records.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["component_id", "flight_date", "duration_min", "landing_cycles", "load_factor", "max_temperature_c", "environment", "notes"])
        for fl in flights:
            if fl["status"] == "completed":
                a = fl["actual"]
                w.writerow([CID, fl["flight_date"], a["duration_min"], a["landing_cycles"], a["load_factor"], round(a["temperature_c"] + 60, 1), a["environment"], f"synthetic revenue flight {fl['id']}"])

    with (ROOT / "example_dataset" / "material_properties.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["component_id", "parameter", "value", "unit", "provenance", "source"])
        w.writerow([CID, "K_IC", 72.0, "MPa√m", "catalogue", "illustrative value of the Ti-6Al-4V class"])
        w.writerow([CID, "paris_m", 3.1, "-", "catalogue", "illustrative"])

    rng = np.random.default_rng(7)
    t = np.arange(0, 600)
    stress = 120 + 80 * np.sin(2 * np.pi * t / 120) + 25 * np.sin(2 * np.pi * t / 7) + rng.normal(0, 6, len(t))
    with (ROOT / "example_dataset" / f"load_history_{CID}.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["component_id", "t_s", "stress_mpa"])
        for ti, si in zip(t, stress):
            w.writerow([CID, int(ti), round(float(si), 2)])
    print("written to", ROOT)


if __name__ == "__main__":
    main()
